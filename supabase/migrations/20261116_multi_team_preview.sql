-- Afon Valley FC multi-team expansion (Chairman-only phase one migration; existing tables preserved)
-- Additive schema. Existing player/ledger/fines data remains untouched.
begin;

create table if not exists public.club_teams (
 id bigint generated by default as identity primary key,
 name text not null unique,
 status text not null default 'draft' check (status in ('draft','active','archived')),
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);
create table if not exists public.club_team_memberships (
 team_id bigint not null references public.club_teams(id),
 player_id bigint not null references public.players(id),
 status text not null default 'active' check(status in ('active','inactive')),
 joined_at timestamptz not null default now(),
 primary key(team_id,player_id)
);
create table if not exists public.club_team_staff (
 team_id bigint not null references public.club_teams(id),
 user_id uuid not null references public.profiles(id),
 staff_role text not null check(staff_role in ('manager','coach','assistant')),
 primary key(team_id,user_id,staff_role)
);
create table if not exists public.club_budget_accounts (
 id bigint generated by default as identity primary key,
 team_id bigint references public.club_teams(id),
 season text not null,
 account_type text not null check(account_type in ('club_reserve','team')),
 opening_pence bigint not null default 0,
 created_at timestamptz not null default now(),
 constraint account_type_team_check check ((account_type='club_reserve' and team_id is null) or (account_type='team' and team_id is not null)),
 unique (team_id, season),
 unique (id, season)
);
create unique index if not exists one_club_reserve_per_season on public.club_budget_accounts(season) where account_type='club_reserve';
create table if not exists public.club_budget_transfers (
 id bigint generated by default as identity primary key,
 from_account_id bigint not null references public.club_budget_accounts(id),
 to_account_id bigint not null references public.club_budget_accounts(id),
 amount_pence bigint not null check(amount_pence>0),
 reason text not null check(length(trim(reason))>0),
 created_by uuid not null references public.profiles(id),
 created_at timestamptz not null default now(),
 check(from_account_id<>to_account_id)
);
create table if not exists public.club_budget_adjustments (
 id bigint generated by default as identity primary key,
 account_id bigint not null references public.club_budget_accounts(id),
 amount_pence bigint not null check(amount_pence<>0),
 reason text not null,
 created_by uuid not null references public.profiles(id),
 created_at timestamptz not null default now()
);
create table if not exists public.club_development_flags (
 user_id uuid not null references public.profiles(id),
 feature text not null,
 enabled boolean not null default false,
 primary key(user_id,feature)
);
alter table public.club_teams enable row level security;
alter table public.club_team_memberships enable row level security;
alter table public.club_team_staff enable row level security;
alter table public.club_budget_accounts enable row level security;
alter table public.club_budget_transfers enable row level security;
alter table public.club_budget_adjustments enable row level security;
alter table public.club_development_flags enable row level security;

-- Chairman-only preview; no other role gets new feature access until rollout.
-- Existing policies and permissions on existing tables are not changed.
create policy "chair_manage_teams" on public.club_teams for all to authenticated
 using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved))
 with check (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved));
create policy "chair_manage_memberships" on public.club_team_memberships for all to authenticated
 using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved))
 with check (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved));
create policy "chair_manage_staff" on public.club_team_staff for all to authenticated
 using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved))
 with check (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved));
create policy "chair_view_budgets" on public.club_budget_accounts for select to authenticated
 using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved));
create policy "chair_view_transfers" on public.club_budget_transfers for select to authenticated
 using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved));
create policy "chair_view_adjustments" on public.club_budget_adjustments for select to authenticated
 using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved));
create policy "chair_flags" on public.club_development_flags for all to authenticated
 using (user_id=(select auth.uid()) and exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved))
 with check (user_id=(select auth.uid()) and exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved));

-- Separate unpublished team fixtures avoid altering legacy matches/RLS until rollout.
create table if not exists public.club_team_fixtures (
 id bigint generated by default as identity primary key,
 team_id bigint not null references public.club_teams(id),
 match_date timestamptz not null,
 opponent text not null check(length(trim(opponent))>0),
 home_away text not null check(home_away in ('Home','Away','Neutral')),
 venue text,
 notes text,
 created_by uuid not null references public.profiles(id),
 created_at timestamptz not null default now()
);
alter table public.club_team_fixtures enable row level security;
create policy "chair_manage_team_fixtures" on public.club_team_fixtures for all to authenticated
 using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved))
 with check (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='chair' and p.approved));

-- First Team is the existing squad; do not change or duplicate historical match records.
insert into public.club_teams(name,status) values ('First Team','active') on conflict (name) do nothing;
insert into public.club_team_memberships(team_id,player_id,status)
select t.id,p.id,'active' from public.club_teams t cross join public.players p
where t.name='First Team' and p.status='active'
on conflict(team_id,player_id) do nothing;

-- Grants allow RLS policies to be evaluated through the Data API.
grant select,insert,update,delete on public.club_teams,public.club_team_memberships,public.club_team_staff,public.club_team_fixtures to authenticated;
grant select on public.club_budget_accounts,public.club_budget_transfers,public.club_budget_adjustments,public.club_development_flags to authenticated;
grant insert,update,delete on public.club_development_flags to authenticated;
grant usage,select on all sequences in schema public to authenticated;

-- Existing matches/training sessions remain unaltered until verified migration.
-- Do not seed fake budgets or infer club cash from player ledger.
commit;
